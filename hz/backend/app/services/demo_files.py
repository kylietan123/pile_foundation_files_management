"""演示文件生成：把种子数据里的一句话，做成**真正能打开**的文件。

**为什么需要这个模块**：
种子数据原来把「演示文件内容：xxx」这句 UTF-8 文本直接标成 `application/pdf`
存进 storage。文件能下载、字节数也不为 0，但用任何 PDF 阅读器打开都是坏的 ——
演示时点开"勘察报告"看到的是乱码/报错，等于把平台的下载能力演示废了。

所以这里用标准库手写一个最小但**合规**的 PDF（单页、Helvetica、A4），
不引入 reportlab 之类的重依赖（本项目的依赖表刻意保持精简）。

限制：**只输出 ASCII 文本**。中文字形需要嵌入 CJK 字体（或依赖阅读器的
系统字体替换），为保证"任何阅读器都能正常显示"，正文统一用英文/编号，
中文标题由平台界面本身呈现（文件名里也保留了编号与版本号）。
"""
from __future__ import annotations

A4_WIDTH = 595
A4_HEIGHT = 842
MARGIN_X = 56
MARGIN_TOP = 800
LINE_HEIGHT = 18
FONT_SIZE = 11
WRAP_CHARS = 88


def _escape(text: str) -> str:
    """PDF 字符串转义；非 ASCII 一律降级为 '?'（见模块说明）。"""
    out = []
    for ch in text:
        if ch in "()\\":
            out.append("\\" + ch)
        elif 32 <= ord(ch) < 127:
            out.append(ch)
        elif ch in ("\t",):
            out.append("    ")
        else:
            out.append("?")
    return "".join(out)


def _wrap(line: str, width: int = WRAP_CHARS) -> list[str]:
    if len(line) <= width:
        return [line]
    return [line[i:i + width] for i in range(0, len(line), width)]


def build_pdf(lines: list[str], title: str | None = None) -> bytes:
    """把若干行文本渲染成一页 A4 PDF，返回 PDF 字节。"""
    content_lines: list[str] = []
    for raw in lines:
        for piece in _wrap(str(raw)):
            content_lines.append(piece)

    # 内容流：从页顶向下逐行绘制
    ops = ["BT", f"/F1 {FONT_SIZE} Tf", f"{LINE_HEIGHT} TL",
           f"{MARGIN_X} {MARGIN_TOP} Td"]
    for i, line in enumerate(content_lines):
        if i:
            ops.append("T*")
        ops.append(f"({_escape(line)}) Tj")
    ops.append("ET")
    stream = "\n".join(ops).encode("latin-1", "replace")

    objects: list[bytes] = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        (
            f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 {A4_WIDTH} {A4_HEIGHT}] "
            f"/Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>"
        ).encode("latin-1"),
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>",
        b"<< /Length " + str(len(stream)).encode() + b" >>\nstream\n" + stream + b"\nendstream",
    ]
    info_title = _escape(title or (lines[0] if lines else "Demo file"))
    objects.append(f"<< /Title ({info_title}) /Producer (PileLCM seed) >>".encode("latin-1"))

    # 组装 + 记录每个对象的字节偏移（xref 必须准确，否则阅读器打不开）
    buf = bytearray(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
    offsets: list[int] = []
    for idx, body in enumerate(objects, start=1):
        offsets.append(len(buf))
        buf += f"{idx} 0 obj\n".encode() + body + b"\nendobj\n"

    xref_pos = len(buf)
    count = len(objects) + 1
    buf += f"xref\n0 {count}\n".encode()
    buf += b"0000000000 65535 f \n"
    for off in offsets:
        buf += f"{off:010d} 00000 n \n".encode()
    buf += (
        f"trailer\n<< /Size {count} /Root 1 0 R /Info {len(objects)} 0 R >>\n"
        f"startxref\n{xref_pos}\n%%EOF\n"
    ).encode()
    return bytes(buf)


def build_demo_file_bytes(text: str, doc_no: str, title: str, version_no: str,
                          state_label: str, project_no: str) -> bytes:
    """演示文件正文：编号/版本/状态这些**能在阅读器里核对**的信息。"""
    return build_pdf(
        [
            "PILE FOUNDATION DOCUMENT PLATFORM — DEMO FILE",
            "",
            f"Document No. : {doc_no}",
            f"Version      : {version_no}",
            f"State        : {state_label}",
            f"Project      : {project_no}",
            "",
            "Note:",
            "  This file is generated by the demo seed so that download / preview",
            "  can be verified end to end. Replace it with a real document by",
            "  uploading a new version in the platform.",
            "",
            f"Seed note: {text}",
        ],
        title=f"{doc_no} {version_no}",
    )
